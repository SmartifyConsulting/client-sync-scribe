export function mergeTranslations<T extends TranslationTree>(base: T, extra?: TranslationTree): T {
  if (!extra) return base;
  const out: TranslationTree = { ...base };
  for (const [key, value] of Object.entries(extra)) {
    out[key] = value && typeof value === "object" && !Array.isArray(value)
      ? mergeTranslations((out[key] ?? {}) as TranslationTree, value)
      : value;
  }
  return out as T;
}
